"""Regression tests for the QA-report fixes that need no database."""
import os
import sys
import unittest

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import legacy_queries as lq  # noqa: E402
import lab_result_import as lri  # noqa: E402
import file_import as fi  # noqa: E402


class TemperatureFahrenheitTests(unittest.TestCase):
    def test_celsius_input_is_converted(self):
        self.assertEqual(lq.normalize_temperature_f("39.4"), 102.9)
        self.assertEqual(lq.normalize_temperature_f(37), 98.6)

    def test_fahrenheit_input_is_kept(self):
        self.assertEqual(lq.normalize_temperature_f("98.6"), 98.6)
        self.assertEqual(lq.normalize_temperature_f("102 °F"), 102.0)

    def test_blank_and_junk_are_dropped(self):
        self.assertIsNone(lq.normalize_temperature_f(""))
        self.assertIsNone(lq.normalize_temperature_f("abc"))
        self.assertIsNone(lq.normalize_temperature_f("200"))

    def test_strict_rejects_out_of_range(self):
        with self.assertRaises(ValueError):
            lq.normalize_temperature_f("200", strict=True)
        with self.assertRaises(ValueError):
            lq.normalize_temperature_f("60", strict=True)


class RegistrationDateTests(unittest.TestCase):
    def test_future_date_rejected(self):
        with self.assertRaises(ValueError):
            lq.parse_registration_date("2999-01-01")

    def test_today_and_blank_mean_no_backdating(self):
        self.assertIsNone(lq.parse_registration_date(""))
        self.assertIsNone(lq.parse_registration_date(lq.current_ist_datetime().strftime("%Y-%m-%d")))

    def test_past_date_is_returned(self):
        self.assertEqual(lq.parse_registration_date("2026-11-15"), "2026-11-15")

    def test_garbage_rejected(self):
        with self.assertRaises(ValueError):
            lq.parse_registration_date("15/11/2026")


class LabImportIdentityTests(unittest.TestCase):
    def test_report_for_another_patient_is_not_filled(self):
        with self.assertRaises(fi.FileImportError) as ctx:
            lri.import_lab_results("r.csv", b"Patient Name;Test Name;Value\nSita Devi;Haemoglobin;9.1\n", [], patient_name="Ravi Kumar")
        self.assertEqual(ctx.exception.status_code, 409)

    def test_empty_catalogue_lists_every_result_as_new_parameter(self):
        out = lri.import_lab_results("r.csv", b"Test,Result,Unit\nFerritin,45,ng/mL\nVitamin D,18,ng/mL\n", [])
        self.assertEqual([p["name"] for p in out["new_parameters"]], ["Ferritin", "Vitamin D"])


class BrandingTests(unittest.TestCase):
    def test_generated_by_label_is_hospai(self):
        src = open(os.path.join(os.path.dirname(__file__), "..", "export_utils.py"), encoding="utf-8").read()
        self.assertIn('("Generated By", "HospAI")', src)
        self.assertNotIn("Hospital System", src)


class StartupMigrationTests(unittest.TestCase):
    def test_fahrenheit_migration_replaces_celsius_one(self):
        import schema_setup
        self.assertIn("migrations_temperature_fahrenheit.sql", schema_setup.MIGRATIONS)
        # The old one would turn Fahrenheit readings back into Celsius at every startup.
        self.assertNotIn("migrations_temperature_celsius.sql", schema_setup.MIGRATIONS)


if __name__ == "__main__":
    unittest.main()
