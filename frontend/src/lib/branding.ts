import { useEffect, useState } from "react";
import { apiFetch } from "./api";
import { setPrintLogoOverride } from "./printBrand";

/** Hospital document branding configured in Admin > Branding & Templates. */
export type BrandingAsset = { mime: string; width_px: number | null; height_px: number | null; url: string; data_uri?: string };
export type PublicWatermark = { modules: string[]; opacity: number; scale_pct: number; width_px: number | null; height_px: number | null; data_uri: string };
export type PublicLogo = {
  id: number;
  name: string;
  alignment: "left" | "center" | "right";
  offset_x_mm: number;
  offset_y_mm: number;
  auto_fit_scaling: boolean;
  modules: string[];
  width_px: number | null;
  height_px: number | null;
  mime: string;
  url: string;
  data_uri?: string;
};
export type PublicFooter = {
  id: number;
  name: string;
  image_url: string | null;
  data_uri?: string;
  width_px: number | null;
  height_px: number | null;
  mime?: string;
  footer_text: string | null;
  modules: string[];
  active: boolean;
};
export type BrandingConfig = {
  watermarks?: PublicWatermark[];
  logos?: PublicLogo[];
  footers?: PublicFooter[];
  configured: boolean;
  hospital_title: string;
  title_font_size_pt?: number | null;
  logo_alignment: "left" | "center" | "right";
  logo_offset_x_mm: number;
  logo_offset_y_mm: number;
  auto_fit_scaling: boolean;
  footer_text: string;
  logo: BrandingAsset | null;
  footer: BrandingAsset | null;
  logo_box_mm: [number, number];
  footer_box_mm: [number, number];
};

let current: BrandingConfig | null = null;
const listeners = new Set<() => void>();

/** React hook: re-renders when the global branding loads or changes. */
export function useBranding(): BrandingConfig | null {
  const [, force] = useState(0);
  useEffect(() => {
    const fn = () => force((n) => n + 1);
    listeners.add(fn);
    return () => { listeners.delete(fn); };
  }, []);
  return getBranding();
}

export function getBranding(): BrandingConfig | null {
  return current && current.configured ? current : null;
}

export function applyBranding(cfg: BrandingConfig | null): void {
  current = cfg;
  setPrintLogoOverride(cfg?.configured ? cfg.logo?.data_uri : null);
  listeners.forEach((fn) => fn());
}

/** Fetch the global branding. Never throws: on any failure the built-in HospAI defaults stay in place. */
export async function loadBranding(): Promise<void> {
  try {
    applyBranding(await apiFetch<BrandingConfig>("/api/branding/public", { background: true }));
  } catch {
    applyBranding(null);
  }
}

export function brandTitle(): string {
  return getBranding()?.hospital_title || "HospAI";
}

export function escapeBrandText(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** Scale (w,h) into a box keeping the aspect ratio; with auto-fit off keep natural 96-dpi size (capped at the page width). */
export function fitMm(wPx: number | null, hPx: number | null, boxW: number, boxH: number, autoFit: boolean): [number, number] {
  if (!wPx || !hPx) return [boxW, boxH];
  const ratio = wPx / hPx;
  let w = autoFit ? Math.min(boxW, boxH * ratio) : Math.min((wPx * 25.4) / 96, 180);
  let h = w / ratio;
  if (h > boxH) { h = boxH; w = h * ratio; }
  return [w, h];
}

/** "Generated By" value: keeps the default wording, short enough to never overflow with a long hospital name. */
export function brandSystemLabel(): string {
  return "HospAI";
}

export function brandThanks(): string {
  return `Thank you for choosing ${brandTitle().replace(/[\r\n]+/g, ", ").replace(/[.\s]+$/, "")}.`;
}


// ---- per-module watermarks ----
/** Which document category (watermark "module") the user is currently working in; set by the app shell on navigation. */
let documentCategory: string | null = null;

export const MODULE_CATEGORY: Record<string, string> = {
  "patient-registration": "op", "queue-management": "op", consultation: "op", "op-management": "op", "doctor-scheduling": "op",
  "follow-up": "op", "doctors-history": "op", patients: "patients", "doctor-prescription": "prescription",
  "bed-management": "ip", "ip-management": "ip", ot: "ip", pharmacy: "pharmacy",
  laboratory: "lab", lab: "lab", "lab-diagnostics": "lab", billing: "billing", finance: "billing", accounts: "billing",
  "insurance-desk": "insurance", emergency: "emergency", dashboard: "reports", reports: "reports", analytics: "reports",
};
const PAGE_CATEGORY: Record<string, string> = { "discharge-summary": "discharge" };

export function setDocumentCategoryForPage(page: string, moduleId?: string | null): void {
  documentCategory = PAGE_CATEGORY[page] || (moduleId ? MODULE_CATEGORY[moduleId] : undefined) || null;
}

export function getDocumentCategory(): string | null {
  return documentCategory;
}

/** Watermark configured for the module the user is in (or for an explicit category), if any. */
export function getActiveWatermark(category: string | null = documentCategory): PublicWatermark | null {
  if (!current?.watermarks || !current.watermarks.length) return null;
  const cat = category ? (MODULE_CATEGORY[category] || category) : null;
  if (!cat) {
    const general = current.watermarks.find((w) => !w.modules?.length || w.modules.includes("all"));
    return general || current.watermarks[0] || null;
  }
  const match = current.watermarks.find((w) => w.modules?.includes(cat) || w.modules?.includes("all") || !w.modules?.length);
  return match || null;
}

/** Logos configured for the current document category / module. Returns all active matching logos. */
export function getActiveLogos(category: string | null = documentCategory): PublicLogo[] {
  if (!current?.logos || !current.logos.length) return [];
  const cat = category ? (MODULE_CATEGORY[category] || category) : null;
  if (!cat) {
    const general = current.logos.filter((l) => !l.modules?.length || l.modules.includes("all"));
    return general.length ? general : current.logos;
  }
  const matching = current.logos.filter((l) => l.modules?.includes(cat) || l.modules?.includes("all"));
  if (matching.length) return matching;
  return current.logos.filter((l) => !l.modules?.length || l.modules.includes("all"));
}

/** Footer configured for the current document category / module. */
export function getActiveFooter(category: string | null = documentCategory): PublicFooter | null {
  if (!current?.footers || !current.footers.length) return null;
  const cat = category ? (MODULE_CATEGORY[category] || category) : null;
  if (!cat) {
    const general = current.footers.find((f) => f.active && (!f.modules?.length || f.modules.includes("all")));
    return general || current.footers.find((f) => f.active) || null;
  }
  const match = current.footers.find((f) => f.active && f.modules?.includes(cat));
  if (match) return match;
  return current.footers.find((f) => f.active && (!f.modules?.length || f.modules.includes("all"))) || null;
}

